USE tk3c_price_tracker;

-- 追蹤清單：固定一批熱門型號，每天到各平台用型號搜尋，增加可以跨平台比價的商品
-- 前 20 名排行榜照舊（price_history / goods_daily），追蹤清單的結果另外存在 watch_price_daily，兩邊互不覆蓋
--   （save_products_to_db 會先刪掉同平台、同分類、當天的排行資料，混在同一張表會互相蓋掉）

CREATE TABLE IF NOT EXISTS watchlist (
    id INT PRIMARY KEY AUTO_INCREMENT,
    分類 VARCHAR(50) NOT NULL,
    廠牌 VARCHAR(100),
    型號 VARCHAR(100) NOT NULL,          -- 搜尋關鍵字；寫法和 goods_daily.型號 相同（大寫、去掉括號）
    啟用 BOOLEAN NOT NULL DEFAULT TRUE,   -- 停產或不想追蹤時改成 FALSE，不用刪除
    建立時間 DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uk_型號 (型號)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 每天、每個平台、每個型號一筆：同型號有多個賣場時取最低價，符合筆數記錄找到幾個賣場
CREATE TABLE IF NOT EXISTS watch_price_daily (
    抓取日期 DATE NOT NULL,
    平台 VARCHAR(20) NOT NULL,           -- tk3c / pchome / yahoo（momo 擋程式存取，不爬）
    分類 VARCHAR(50) NOT NULL,
    型號 VARCHAR(100) NOT NULL,          -- watchlist.型號
    商品編號 VARCHAR(50) NOT NULL,
    廠牌 VARCHAR(100),
    商品名稱 VARCHAR(255),
    售價 INT NOT NULL,
    原價 INT,
    符合筆數 INT NOT NULL,
    連結 VARCHAR(500),
    PRIMARY KEY (抓取日期, 平台, 型號),
    INDEX idx_分類_日期 (分類, 抓取日期),
    INDEX idx_型號 (型號)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

